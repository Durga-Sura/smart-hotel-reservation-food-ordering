CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(80) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS hotels (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, owner_id BIGINT UNIQUE, name VARCHAR(100) NOT NULL,
 location VARCHAR(150) NOT NULL, description VARCHAR(500) NOT NULL, cuisine VARCHAR(100) NOT NULL,
 opens VARCHAR(5) NOT NULL DEFAULT '12:00', closes VARCHAR(5) NOT NULL DEFAULT '23:00', image VARCHAR(1000),
 FOREIGN KEY(owner_id) REFERENCES app_users(id)
);
CREATE TABLE IF NOT EXISTS dining_tables (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, hotel_id BIGINT NOT NULL, name VARCHAR(20) NOT NULL,
 capacity INT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'Available', active BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(hotel_id,name), FOREIGN KEY(hotel_id) REFERENCES hotels(id)
);
CREATE TABLE IF NOT EXISTS menu_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, hotel_id BIGINT NOT NULL, name VARCHAR(100) NOT NULL,
 category VARCHAR(30) NOT NULL, price DECIMAL(10,2) NOT NULL, description VARCHAR(500) NOT NULL,
 image VARCHAR(1000), available BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY(hotel_id) REFERENCES hotels(id)
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, hotel_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
 table_id BIGINT NOT NULL, guest VARCHAR(80) NOT NULL, email VARCHAR(190) NOT NULL, guests INT NOT NULL,
 visit_date DATE NOT NULL, visit_time VARCHAR(5) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'Confirmed',
 notes VARCHAR(500), total DECIMAL(10,2) NOT NULL DEFAULT 0, payment_method VARCHAR(30) NOT NULL DEFAULT 'PAY_AT_HOTEL',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(hotel_id) REFERENCES hotels(id),
 FOREIGN KEY(user_id) REFERENCES app_users(id), FOREIGN KEY(table_id) REFERENCES dining_tables(id),
 INDEX reservation_slot(table_id,visit_date,status)
);
CREATE TABLE IF NOT EXISTS food_orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, reservation_id BIGINT NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'Pending', FOREIGN KEY(reservation_id) REFERENCES reservations(id)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, reservation_id BIGINT NOT NULL, menu_item_id BIGINT NOT NULL,
 quantity INT NOT NULL, unit_price DECIMAL(10,2) NOT NULL, item_name VARCHAR(100) NOT NULL,
 FOREIGN KEY(reservation_id) REFERENCES reservations(id), FOREIGN KEY(menu_item_id) REFERENCES menu_items(id)
);
